import {chromium} from './support/playwright.mjs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {previewPNG} from './preview-png-fixture.mjs';

const root = path.resolve('.'), out = path.join(root, 'artifacts/adaptive-preview');
await mkdir(out, {recursive: true});
await writeFile(path.join(out, 'large.png'), await previewPNG(8192, 4096));
const {startBackend} = createRequire(import.meta.url)('../desktop/backend.cjs');
const backend = await startBackend({appRoot: root}); let browser;
try {
  browser = await chromium.launch({channel: 'chrome', headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 960}}), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(backend.origin); await page.waitForFunction(() => window.styk?.ready);
  const result = await page.evaluate(async () => {
    const {PlaybackResources} = await import('/src/playback-resources.mjs');
    const {compilePlaybackPacket} = await import('/src/playback-worker.mjs');
    const {PlaybackCache} = await import('/src/playback.mjs');
    const {createImageFigure} = await import('/src/media-authoring.mjs');
    const {emptyDocument, createFrame, createObject} = await import('/src/demo.mjs');
    const {exportFrameGeometry, drawExportScene, drawExportSceneSequential, drawExportSceneTiled} = await import('/src/export-frame-core.mjs');
    const check = (condition, message) => {if (!condition) throw new Error(message);};
    const blob = await (await fetch('/artifacts/adaptive-preview/large.png')).blob();
    const dataUrl = await new Promise(resolve => {const reader = new FileReader(); reader.onload = () => resolve(reader.result); reader.readAsDataURL(blob);});
    const sprite = createImageFigure({dataUrl, width: 8192, height: 4096, maxPixels: 8192 * 4096});
    const report = emptyDocument(); report.figure_types = [sprite];
    report.keyframes = [0,1,2,3].map(i => createFrame([createObject(sprite, 1, 470 + i * 3, 270, {scale: .08, field28: 40})]));
    const original = JSON.stringify(report);
    const resources = new PlaybackResources({preview: true, maxBytes: 1024 * 1024});
    const item = {type: 'image', asset: sprite.image_assets[0]};
    await resources.preload([item], {scale: .01});
    const small = resources.image(dataUrl), firstWidth = small.width;
    check(small.naturalWidth === 8192 && small.width < 256, 'Preview changed logical size or decoded full source.');
    await resources.preload([item], {scale: .2});
    const larger = resources.image(dataUrl);
    check(larger.width > firstWidth && resources.bytes <= resources.maxBytes, 'Zoom detail did not grow within budget.');
    const zoomWidth = larger.width;
    await resources.preload([item], {scale: .2});
    check(resources.image(dataUrl) === larger, 'An unchanged preview was unnecessarily decoded again.');
    const second = {...item, asset: {...item.asset, url: '/artifacts/adaptive-preview/large.png', data_url: undefined}};
    await resources.preload([item, second], {scale: 1});
    check(resources.bytes <= resources.maxBytes && resources.images.size === 2, 'Distinct simultaneous images exceeded their shared budget.');
    const packet = await compilePlaybackPacket(report, 0, {resources, maxPacketBytes: 32 * 1024, scale: 4});
    check(packet.previewQuality.reduced && packet.byteLength <= 32 * 1024, 'Oversized frame did not recover within budget.');
    check(packet.compatibility[0].bitmap.width > 0 && packet.uids.includes(1), 'Recovery omitted the animated figure.');
    for (const entry of packet.compatibility) entry.bitmap.close();
    resources.dispose();
    const cache = new PlaybackCache({maxBytes: 128 * 1024});
    cache.load(report, {scale: 4}); await cache.prepareRange([0,1,2,3]);
    check(cache.stats.preparedFrames === 4 && cache.stats.bytes <= cache.maxBytes, 'Worker failed to prepare consecutive frames.');
    const worker = {...cache.stats}; cache.dispose();
    const full = new PlaybackResources({maxBytes: 1024 * 1024, preview: false});
    const geometry = exportFrameGeometry(report, report.keyframes[0]);
    await full.preload(geometry.drawables);
    check(full.image(dataUrl).width === 8192, 'Export received preview pixels.');
    const expected = new OffscreenCanvas(960, 540), actual = new OffscreenCanvas(960, 540);
    drawExportScene(expected.getContext('2d'), report, report.keyframes[0], geometry, full);
    await drawExportSceneSequential(actual.getContext('2d'), report, report.keyframes[0], geometry, full);
    const a = actual.getContext('2d').getImageData(0,0,960,540).data, b = expected.getContext('2d').getImageData(0,0,960,540).data;
    let different = 0; for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) different++;
    check(different === 0, `Sequential export changed ${different} channels.`);
    await drawExportSceneTiled(actual.getContext('2d'), report, report.keyframes[0], geometry, full, 256);
    const tiled = actual.getContext('2d').getImageData(0,0,960,540).data;
    let tileDifferences = 0; for (let i = 0; i < tiled.length; i++) if (tiled[i] !== b[i]) tileDifferences++;
    check(tileDifferences === 0, `Tiled export changed ${tileDifferences} channels.`); full.dispose();
    check(JSON.stringify(report) === original, 'Preview mutated the original document.');
    styk.editor.markSaved(); await styk.acceptImport({document: report, kind: 'piv'}, 'Large-image preview.piv');
    return {sourceBytes: 8192 * 4096 * 4, firstWidth, zoomWidth, recoveredBytes: packet.byteLength, quality: packet.previewQuality, worker, exportDifferentChannels: different, tiledExportDifferentChannels: tileDifferences};
  });
  await page.waitForTimeout(1200);
  await page.locator('#play-button').click();
  await page.waitForFunction(() => styk.state.playing && styk.editor.tick > 0);
  await page.screenshot({path: path.join(out, 'playback.png')});
  await page.locator('#play-button').click();
  await page.waitForFunction(() => !styk.state.playing && !styk.state.editablePreparing);
  await page.locator('[data-field="root_x"]').fill('490'); await page.locator('[data-field="root_x"]').press('Tab');
  assert.equal(await page.evaluate(() => styk.editor.object.root_x), 490);
  await page.keyboard.press('Control+z');
  assert.notEqual(await page.evaluate(() => styk.editor.object.root_x), 490);
  await page.screenshot({path: path.join(out, 'editing.png')});
  await page.evaluate(() => {
    styk.state.renderer.rasterCache.maxBytes = 64 * 1024;
    styk.state.renderer.lastGeometry = null;
    styk.state.dirtyRender = true;
    styk.fit();
  });
  await page.waitForFunction(() => !document.getElementById('preview-quality').hidden);
  const editable = await page.evaluate(() => ({activeBytes: styk.state.renderer.stats.editorRasterCache.activeBytes,
    maxBytes: styk.state.renderer.rasterCache.maxBytes, handles: styk.editor.geometry.handles?.length || styk.state.renderer.stats.handleCount,
    quality: styk.state.renderer.stats.previewReduced}));
  assert.ok(editable.activeBytes <= editable.maxBytes && editable.quality && editable.handles > 0);
  await page.screenshot({path: path.join(out, 'reduced-editing.png')});
  result.editableMemory = editable;
  assert.deepEqual(errors, []);
  await writeFile(path.join(out, 'result.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify({...result, editingAndUndo: true, pageErrors: errors}, null, 2));
} finally {await browser?.close(); backend.stop();}
