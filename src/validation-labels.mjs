/** Resolve a known human label without interpreting document fields or values. */
export function validationLabel(label) {
  const known = labels.get(label);
  if (known) return known;
  if (typeof label !== 'string') return label;
  for (const [prefix, messageKey] of fieldLabels) {
    if (label.startsWith(prefix)) return {messageKey, messageParams:{field:label.slice(prefix.length)}, diagnosticValue:label};
  }
  return label;
}

